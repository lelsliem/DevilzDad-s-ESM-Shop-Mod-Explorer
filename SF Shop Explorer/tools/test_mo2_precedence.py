#!/usr/bin/env python3
"""Guard for MO2 conflict precedence in the previewer.

`DiscoverMoMods` used to collect enabled mod names into a set and then walk the
mods folder in directory order, so when two mods shipped the same NIF, .mat or
texture the preview picked an alphabetical winner. The engine does not: MO2
stores priority implicitly in modlist.txt, reversed - the LAST line is
priority 0 and the FIRST line wins every loose-file conflict. In the
2026-10-23 profile that changed the winner for 31 loose files and 2,731
archive entries (the audit tool reports both numbers).

The test pins the profile-order rule and the C++ path that consumes it.

    python -m unittest test_mo2_precedence -v
"""
from __future__ import annotations

import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import mo2_audit  # noqa: E402

LIVE_MODEL = ROOT / "src" / "LiveModel.cpp"


class ProfileOrderTests(unittest.TestCase):
    def test_first_line_is_the_winner(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            profiles = Path(tmp) / "profiles"
            profile = profiles / "P"
            profile.mkdir(parents=True)
            (profile / "modlist.txt").write_text(
                "# This file was automatically generated by Mod Organizer.\n"
                "+Zulu Outfit\n"
                "+Alpha Texture Pack\n"
                "-Disabled Thing\n"
                "+Beta_separator\n",
                encoding="utf-8")
            with mock.patch.object(mo2_audit, "PROFILES", profiles):
                enabled, disabled = mo2_audit.profile_order("P")
            self.assertEqual(enabled, ["Zulu Outfit", "Alpha Texture Pack"])
            self.assertEqual(disabled, ["Disabled Thing"])
            # Zulu wins the conflict even though Alpha sorts first on disk.
            self.assertEqual(enabled[0], "Zulu Outfit")


class SourceTests(unittest.TestCase):
    def test_plugin_reads_no_manager_configuration(self) -> None:
        """The plugin must not guess at a mod manager's configuration.

        Assets come from the Data view this process sees: a manager's VFS has
        already merged and priority-resolved it, so exactly one file exists per
        path and it is the one the game loads. Parsing ModOrganizer.ini or a
        profile's modlist.txt guessed a second time at the same answer, and was
        wrong whenever the profile name, the manager or the layout differed -
        which is how the shop ended up disagreeing with the game.
        """
        src = LIVE_MODEL.read_text(encoding="utf-8")
        code = "\n".join(
            line for line in src.splitlines() if not line.lstrip().startswith("//")
        )
        for forbidden in (
            "ModOrganizer.ini",
            "selected_profile",
            "modlist.txt",
            "enabledOrder",
            "g_moBa2",
            "g_moDirs",
        ):
            self.assertNotIn(forbidden, code, f"LiveModel.cpp still reads {forbidden}")
        # The loaded view is the source of truth, and it must be read.
        self.assertIn("g_dataDir", code)


if __name__ == "__main__":
    unittest.main()
