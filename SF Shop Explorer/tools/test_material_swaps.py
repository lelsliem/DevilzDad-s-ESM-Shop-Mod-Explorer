"""Regression tests for the layered-material-swap table and its key form.

The table is generated by gen_material_swaps.py and read by
SFE::LiveModel::MaterialSwapFor. Both sides have to agree on one thing: the
material key. A mismatch is silent - the preview simply keeps the stock
material - so the key rule is asserted here rather than left to in-game
inspection.

    python -m unittest test_material_swaps -v
    python test_material_swaps.py
"""
from __future__ import annotations

import unittest
from pathlib import Path

import gen_material_swaps as gen

TABLE = Path(__file__).resolve().parent / "materialswaps.tsv"


def swap_key(path: str) -> str:
    """Replica of SFE::LiveModel::SwapKey (src/LiveModel.cpp)."""
    s = path.lower().replace("\\", "/").lstrip("/ ")
    if s.startswith("data/"):
        s = s[5:]
    if s.startswith("materials/"):
        s = s[10:]
    colon = s.rfind(":")
    if colon >= 0:
        s = s[:colon]
    if s.endswith(".mat"):
        s = s[:-4]
    return s


def rows() -> list[tuple[int, str, str]]:
    out = []
    for line in TABLE.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        form, key, override = line.split("\t")
        out.append((int(form, 16), key, override))
    return out


class KeyFormTests(unittest.TestCase):
    def test_nif_path_and_esm_path_agree(self) -> None:
        # The NIF says Materials\Clothes\X.mat, the swap table says
        # Clothes\X.mat: both must collapse to the same key or the preview
        # never applies the override.
        self.assertEqual(
            swap_key("Materials\\Clothes\\Outfit_Trucker_Tee\\Outfit_Trucker_Tee_Upperbody.mat"),
            swap_key("Clothes\\Outfit_Trucker_Tee\\Outfit_Trucker_Tee_Upperbody.mat"),
        )

    def test_geometry_suffix_and_case_are_ignored(self) -> None:
        self.assertEqual(swap_key("materials/actors/human/hands/DefaultHandsF.mat:0"),
                         "actors/human/hands/defaulthandsf")
        self.assertEqual(swap_key("DATA\\Materials\\A\\B.mat"), "a/b")


class PairingTests(unittest.TestCase):
    def test_material_strings_pair_in_key_override_order(self) -> None:
        blob = (
            b"BETHRest\0"
            b"Clothes\\Outfit_Trucker_Tee\\Outfit_Trucker_Tee_Upperbody.mat\0"
            b"Clothes\\Outfit_Trucker_Tee\\Outfit_Trucker_Tee_Resort_Upperbody.mat\0"
            b"Clothes\\Outfit_Neon_BusinessSuit_01\\Outfit_Neon_BusinessSuit_LowerBody_01.mat\0"
            b"Clothes\\Outfit_Neon_BusinessSuit_01\\Outfit_Neon_BusinessSuit_LowerBody_Resort.mat\0"
        )
        self.assertEqual(
            gen.material_pairs(blob),
            [
                ("Clothes\\Outfit_Trucker_Tee\\Outfit_Trucker_Tee_Upperbody.mat",
                 "Clothes\\Outfit_Trucker_Tee\\Outfit_Trucker_Tee_Resort_Upperbody.mat"),
                ("Clothes\\Outfit_Neon_BusinessSuit_01\\Outfit_Neon_BusinessSuit_LowerBody_01.mat",
                 "Clothes\\Outfit_Neon_BusinessSuit_01\\Outfit_Neon_BusinessSuit_LowerBody_Resort.mat"),
            ],
        )


class ShippedTableTests(unittest.TestCase):
    """The five garments from the 2026-10-18 capture must be in the table."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.table = rows() if TABLE.exists() else []
        cls.by_form: dict[int, dict[str, str]] = {}
        for form, key, override in cls.table:
            cls.by_form.setdefault(form, {})[swap_key(key)] = override

    def test_table_is_well_formed(self) -> None:
        if not self.table:
            self.skipTest("materialswaps.tsv not generated on this machine")
        for form, key, override in self.table:
            self.assertTrue(key.lower().endswith(".mat"), key)
            self.assertTrue(override.lower().endswith(".mat"), override)
            self.assertNotEqual(swap_key(key), swap_key(override))
        # No duplicate key per form: a second row could never be reached.
        for form, pairs in self.by_form.items():
            self.assertEqual(len(pairs), len({k for k in pairs}))

    def test_resort_wear_tee_and_trousers(self) -> None:
        if not self.table:
            self.skipTest("materialswaps.tsv not generated on this machine")
        swapped = self.by_form[0x3BF6]
        self.assertEqual(
            swap_key(swapped["clothes/outfit_trucker_tee/outfit_trucker_tee_upperbody"]),
            "clothes/outfit_trucker_tee/outfit_trucker_tee_resort_upperbody",
        )
        self.assertEqual(
            swap_key(swapped["clothes/outfit_neon_businesssuit_01/outfit_neon_businesssuit_lowerbody_01"]),
            "clothes/outfit_neon_businesssuit_01/outfit_neon_businesssuit_lowerbody_resort",
        )

    def test_star_roamer_uses_the_generic_materials(self) -> None:
        if not self.table:
            self.skipTest("materialswaps.tsv not generated on this machine")
        for form, part in ((0x3E8F, "helmet"), (0x4E78, "upperbody")):
            swapped = self.by_form[form]
            key = f"clothes/spacesuit_spacetrucker/spacesuit_spacetrucker_{part}"
            self.assertIn(key, swapped)
            self.assertEqual(swap_key(swapped[key]),
                             f"clothes/spacesuit_spacetrucker/generic/spacesuit_generic_{part}")

    def test_synth_leatherwear_jacket_is_the_orange_one(self) -> None:
        if not self.table:
            self.skipTest("materialswaps.tsv not generated on this machine")
        swapped = self.by_form[0x9CC6]
        key = "clothes/outfit_civilian_rubberpocketpants/outfit_civilian_rubberpocketpants_jacket"
        self.assertIn(key, swapped)
        self.assertEqual(swap_key(swapped[key]), key + "orange")


if __name__ == "__main__":
    unittest.main()
